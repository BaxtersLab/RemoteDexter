//! Cross-language canonical-byte vectors.
//!
//! ## Why this file exists
//!
//! The Rust host signs; the Kotlin client verifies. If their canonical byte
//! encodings diverge by one character, **every signature simply fails to
//! verify** — and it fails silently, on a phone, as "pairing didn't work",
//! with both sides compiling perfectly and both sides' own tests green.
//!
//! `contract/signed_invite_v4.json` is the shared fixture. This file asserts
//! Rust produces it; `InviteVectorTest.kt` asserts Kotlin produces the same
//! bytes and verifies the same signature. Neither side imports the other.
//!
//! The fixture also contains a **Kotlin-generated** vector, verified here by
//! Rust, so the agreement is proven in both directions rather than one side
//! being defined as correct.

use pairing::invite::canonical_bytes;
use pairing::{signature_is_valid, INVITE_KIND, INVITE_VERSION};

const FIXTURE: &str = include_str!("../../../contract/signed_invite_v4.json");

fn fixture() -> serde_json::Value {
    serde_json::from_str(FIXTURE).expect("contract/signed_invite_v4.json is valid JSON")
}

/// The canonical bytes Rust produces for the shared vector, byte for byte.
#[test]
fn rust_reproduces_the_shared_canonical_bytes() {
    let f = fixture();
    let v = &f["rust_generated"];
    let caps: Vec<String> = v["capabilities"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| c.as_str().unwrap().to_string())
        .collect();

    let produced = canonical_bytes(
        v["kind"].as_str().unwrap(),
        v["version"].as_u64().unwrap() as u8,
        v["protocol"].as_str().unwrap(),
        v["addr"].as_str().unwrap(),
        v["port"].as_u64().unwrap() as u16,
        v["token"].as_str().unwrap(),
        v["nonce"].as_str().unwrap(),
        v["expires_at"].as_u64().unwrap(),
        &caps,
        v["host_pubkey"].as_str().unwrap(),
    );

    let expected = f["rust_generated"]["canonical_utf8"].as_str().unwrap();
    assert_eq!(
        String::from_utf8(produced.clone()).unwrap(),
        expected,
        "canonical bytes drifted from the checked-in vector"
    );

    // And the recorded signature verifies over exactly those bytes.
    assert!(
        signature_is_valid(
            &produced,
            v["host_identity_pubkey"].as_str().unwrap(),
            v["signature"].as_str().unwrap()
        ),
        "the recorded signature must verify over the recorded bytes"
    );
}

/// The vector generated by the Kotlin side, verified here. This is the
/// direction that catches "Rust is self-consistently wrong".
#[test]
fn rust_verifies_the_kotlin_generated_vector() {
    let f = fixture();
    let v = &f["kotlin_generated"];
    let caps: Vec<String> = v["capabilities"]
        .as_array()
        .unwrap()
        .iter()
        .map(|c| c.as_str().unwrap().to_string())
        .collect();

    let produced = canonical_bytes(
        v["kind"].as_str().unwrap(),
        v["version"].as_u64().unwrap() as u8,
        v["protocol"].as_str().unwrap(),
        v["addr"].as_str().unwrap(),
        v["port"].as_u64().unwrap() as u16,
        v["token"].as_str().unwrap(),
        v["nonce"].as_str().unwrap(),
        v["expires_at"].as_u64().unwrap(),
        &caps,
        v["host_pubkey"].as_str().unwrap(),
    );
    assert_eq!(
        String::from_utf8(produced.clone()).unwrap(),
        v["canonical_utf8"].as_str().unwrap(),
        "Rust and Kotlin disagree on the canonical encoding"
    );
    assert!(signature_is_valid(
        &produced,
        v["host_identity_pubkey"].as_str().unwrap(),
        v["signature"].as_str().unwrap()
    ));
}

/// The fixture's own shape. A vector file that quietly loses a field would make
/// both sides agree about nothing.
#[test]
fn the_fixture_covers_every_signed_field() {
    let f = fixture();
    for side in ["rust_generated", "kotlin_generated"] {
        let v = &f[side];
        for field in [
            "kind",
            "version",
            "protocol",
            "addr",
            "port",
            "token",
            "nonce",
            "expires_at",
            "capabilities",
            "host_pubkey",
            "host_identity_pubkey",
            "signature",
            "canonical_utf8",
        ] {
            assert!(!v[field].is_null(), "{side} is missing {field}");
        }
        assert_eq!(v["kind"].as_str().unwrap(), INVITE_KIND);
        assert_eq!(v["version"].as_u64().unwrap() as u8, INVITE_VERSION);
    }
}

/// Negative controls carried in the fixture: each must fail to verify. Without
/// these the file could record a signature over the wrong bytes and every
/// positive test would still pass.
#[test]
fn the_fixtures_negative_controls_all_fail() {
    let f = fixture();
    for case in f["negative"].as_array().unwrap() {
        let name = case["name"].as_str().unwrap();
        let caps: Vec<String> = case["capabilities"]
            .as_array()
            .unwrap()
            .iter()
            .map(|c| c.as_str().unwrap().to_string())
            .collect();
        let produced = canonical_bytes(
            case["kind"].as_str().unwrap(),
            case["version"].as_u64().unwrap() as u8,
            case["protocol"].as_str().unwrap(),
            case["addr"].as_str().unwrap(),
            case["port"].as_u64().unwrap() as u16,
            case["token"].as_str().unwrap(),
            case["nonce"].as_str().unwrap(),
            case["expires_at"].as_u64().unwrap(),
            &caps,
            case["host_pubkey"].as_str().unwrap(),
        );
        assert!(
            !signature_is_valid(
                &produced,
                case["host_identity_pubkey"].as_str().unwrap(),
                case["signature"].as_str().unwrap()
            ),
            "negative control `{name}` VERIFIED — it must not"
        );
    }
}
