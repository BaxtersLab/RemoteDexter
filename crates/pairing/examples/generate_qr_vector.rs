//! Prints `contract/qr_modules_v1.json`: QR module grids exactly as
//! `pairing::qr::encode` draws them, for the Android side to decode with the
//! scanner's own ZXing.
//!
//! cargo run -q -p pairing --example generate_qr_vector > contract/qr_modules_v1.json

// The cases live with the test that checks this file, so the two cannot drift.
#[path = "../tests/common/mod.rs"]
mod qr_vector_cases;

fn main() {
    let cases: Vec<serde_json::Value> = qr_vector_cases::cases()
        .into_iter()
        .map(|(name, path, text)| {
            let rows = qr_vector_cases::symbol_rows(&text);
            serde_json::json!({
                "name": name,
                "path": path,
                "text": text,
                "symbol_size": rows.len(),
                "rows": rows,
            })
        })
        .collect();
    let doc = serde_json::json!({
        "_note": "Generated by crates/pairing/examples/generate_qr_vector.rs. Each case is the \
                  symbol WITHOUT its 4-module quiet zone, one string per row, '1' = dark. \
                  Rust (tests/qr_vectors.rs) checks these are exactly what pairing::qr::encode \
                  draws; Android (QrModulesTest.kt) decodes them with ZXing, the library the \
                  phone scans with. 'path' names which encoding encode() chose.",
        "cases": cases,
    });
    println!(
        "{}",
        serde_json::to_string_pretty(&doc).expect("serializable")
    );
}
